const mongoose = require('mongoose');

const reportSchema = new mongoose.Schema(
  {
    reportNumber: {
      type: String,
      required: true,
      unique: true,
      trim: true,
      uppercase: true,
      index: true,
    },
    title: {
      ar: { type: String, required: true },
      fr: { type: String, required: true },
      en: { type: String, required: true },
    },
    frequency: {
      type: String,
      enum: ['DAILY', 'WEEKLY', 'MONTHLY', 'MANUAL'],
      default: 'MANUAL',
      index: true,
    },
    type: {
      type: String,
      enum: ['INVENTORY_SUMMARY', 'SHIPMENTS_SUMMARY', 'DELAYS_INCIDENTS', 'MOVEMENTS_VOLUME', 'EMPLOYEE_PERFORMANCE'],
      required: true,
      index: true,
    },
    dataSnapshot: {
      type: mongoose.Schema.Types.Mixed,
      required: true,
    },
    generatedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      default: null, // Null if generated by node-cron system
    },
    generatedByName: {
      type: String,
      default: 'Automated Cron Engine (LogiNaft)',
    },
    periodStart: { type: Date },
    periodEnd: { type: Date },
    timestamp: {
      type: Date,
      default: Date.now,
      index: true,
    },
  },
  {
    timestamps: true,
  }
);

module.exports = mongoose.model('Report', reportSchema);
